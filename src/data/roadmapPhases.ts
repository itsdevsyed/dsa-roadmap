const topicToPhaseMap = new Map<string, PhaseInfo>();
ROADMAP_PHASES.forEach((phase) => {
  phase.topics.forEach((topic) => {
    topicToPhaseMap.set(topic, phase);
  });
});

export function getPhaseForTopic(topic: string): PhaseInfo {
  return (
    topicToPhaseMap.get(topic) || {
      id: 1,
      title: 'Phase 1: Foundations',
      shortTitle: 'Foundations',
      description: 'Core foundational data structures & techniques',
      accentColor: 'emerald',
      topics: [topic],
    }
  );
}

